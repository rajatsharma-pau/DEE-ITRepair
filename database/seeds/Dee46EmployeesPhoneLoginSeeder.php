            $data['cadre'] = 'DEE';
        }
        return DB::table('designations')->insertGetId($this->onlyExistingColumns('designations', $data));
    }

    protected function ensureRole($slug, $name)
    {
        if (!Schema::hasTable('roles')) {
            return null;
        }
        $role = DB::table('roles')->where('slug', $slug)->orWhere('name', $name)->first();
        if ($role) {
            return $role->id;
        }
        $data = [
            'name' => $name,
            'slug' => $slug,
            'created_at' => now(),
            'updated_at' => now(),
        ];
        return DB::table('roles')->insertGetId($this->onlyExistingColumns('roles', $data));
    }

    protected function attachRole($userId, $roleId)
    {
        if (!$roleId || !Schema::hasTable('user_roles')) {
            return;
        }
        $exists = DB::table('user_roles')->where('user_id', $userId)->where('role_id', $roleId)->exists();
        if (!$exists) {
            DB::table('user_roles')->insert([
                'user_id' => $userId,
                'role_id' => $roleId,
                'created_at' => now(),
                'updated_at' => now(),
            ]);
        }
    }

    protected function seedPromotionHistory($employeeId, array $record)
    {
        if (!$employeeId || !Schema::hasTable('employee_service_movements')) {
            return;
        }
        $json = $record['past_promotions_json'];
        if (!$json) {
            return;
        }
        $items = json_decode($json, true);
        if (!is_array($items)) {
            return;
        }
        foreach ($items as $item) {
            if (empty($item['date']) && empty($item['detail']) && empty($item['details'])) {
                continue;
            }
            $effectiveDate = isset($item['date']) ? $item['date'] : null;
            $detail = isset($item['detail']) ? $item['detail'] : (isset($item['details']) ? $item['details'] : null);
            $already = DB::table('employee_service_movements')
                ->where('employee_id', $employeeId)
                ->where('movement_type', 'Promotion')
                ->where('effective_date', $effectiveDate)
                ->where('remarks', $detail)
                ->exists();
            if (!$already) {
                $data = [
                    'employee_id' => $employeeId,
                    'movement_type' => 'Promotion',
                    'effective_date' => $effectiveDate,
                    'remarks' => $detail,
                    'created_at' => now(),
                    'updated_at' => now(),
                ];
                DB::table('employee_service_movements')->insert($this->onlyExistingColumns('employee_service_movements', $data));
            }
        }
    }
