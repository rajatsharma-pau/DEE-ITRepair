    protected function validatePhones(array $records)
    {
        $phones = [];
        foreach ($records as $record) {
            $phone = $this->normalizePhone($record['phone']);
            if (!$phone || strlen($phone) !== 10) {
                throw new Exception('Invalid/missing phone for employee: ' . $record['employee_name']);
            }
            if (isset($phones[$phone])) {
                throw new Exception('Duplicate phone number ' . $phone . ' for ' . $phones[$phone] . ' and ' . $record['employee_name']);
            }
            $phones[$phone] = $record['employee_name'];
        }
    }

    protected function normalizePhone($phone)
    {
        $phone = preg_replace('/\D+/', '', (string) $phone);
        if (strlen($phone) > 10 && substr($phone, 0, 2) === '91') {
            $phone = substr($phone, -10);
        }
        return $phone;
    }

    protected function findUserByPhone($phone)
    {
        if (!Schema::hasColumn('users', 'phone')) {
            return null;
        }
        return DB::table('users')->where('phone', $phone)->first();
    }

    protected function onlyExistingColumns($table, array $data)
    {
        $filtered = [];
        foreach ($data as $column => $value) {
            if (Schema::hasColumn($table, $column)) {
                $filtered[$column] = $value;
            }
        }
        return $filtered;
    }

    protected function upsertEmployee(array $employeeData, $phone, $personalFileNumber)
    {
        $existing = null;

        if (Schema::hasColumn('employees', 'user_id') && isset($employeeData['user_id'])) {
            $existing = DB::table('employees')->where('user_id', $employeeData['user_id'])->first();
        }
        if (!$existing && $personalFileNumber && Schema::hasColumn('employees', 'personal_file_number')) {
            $existing = DB::table('employees')->where('personal_file_number', $personalFileNumber)->first();
        }
        if (!$existing && $phone && Schema::hasColumn('employees', 'phone')) {
            $existing = DB::table('employees')->where('phone', $phone)->first();
        }

        $data = $this->onlyExistingColumns('employees', $employeeData);

        if ($existing) {
            DB::table('employees')->where('id', $existing->id)->update($data);
            return $existing->id;
        }

        if (Schema::hasColumn('employees', 'created_at')) {
            $data['created_at'] = now();
        }
        if (Schema::hasColumn('employees', 'updated_at') && !isset($data['updated_at'])) {
            $data['updated_at'] = now();
        }

        return DB::table('employees')->insertGetId($data);
    }

    protected function ensureCollege($name)
    {
        if (!Schema::hasTable('colleges')) {
            return null;
        }
        $college = DB::table('colleges')->where('name', $name)->first();
        if ($college) {
            return $college->id;
        }
        return DB::table('colleges')->insertGetId([
            'name' => $name,
            'created_at' => now(),
            'updated_at' => now(),
        ]);
    }

    protected function ensureDepartment($collegeId, $name, $place)
    {
        if (!Schema::hasTable('departments')) {
            return null;
        }
        $query = DB::table('departments')->where('name', $name);
        if (Schema::hasColumn('departments', 'college_id') && $collegeId) {
            $query->where('college_id', $collegeId);
        }
        $dept = $query->first();
        if ($dept) {
            return $dept->id;
        }

        $data = [
            'name' => $name,
            'place' => $place,
            'created_at' => now(),
            'updated_at' => now(),
        ];
        if (Schema::hasColumn('departments', 'college_id')) {
            $data['college_id'] = $collegeId;
        }
        return DB::table('departments')->insertGetId($data);
    }

